function sample(id, title, article, reference, constraints, weights = []) {
  const sources = article.match(/[^。！？]+[。！？]?/g).map((text, index) => ({ id: `S${index + 1}`, text: text.trim() }));
  return {
    id, title, article, reference, reviewStatus: "author-curated; awaiting independent human review",
    sources,
    facts: sources.map((source, index) => ({ id: `F${index + 1}`, text: source.text, weight: weights[index] || 1, evidenceIds: [source.id] })),
    constraints: constraints.map((text, index) => ({ id: `K${index + 1}`, text,
      evidenceIds: sources.filter(source => source.text.includes(text)).map(source => source.id) }))
  };
}

