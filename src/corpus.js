function pick(corpus, date, count, suffix = false) {
  const days = Math.floor(Date.parse(`${date}T00:00:00Z`) / 86400000);
  if (!Number.isFinite(days)) throw new Error("Invalid experiment date");
  const start = ((days * count) % corpus.length + corpus.length) % corpus.length;
  return Array.from({ length: count }, (_, index) => {
    const item = corpus[(start + index) % corpus.length];
    return suffix ? { ...item, id: `${item.id}-${date}` } : item;
  });
}

